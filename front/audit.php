<?php

/**
 * Audit evidence: seven sections for one period, for the mandatory ("Wajib Backup") Computers in the
 * user's active entities. The page opens at once and fills each section with its own request
 * (?section=<key>), the fast GLPI ones first. Exports: ?export=<section>|all, as Excel (default) or
 * CSV (&format=csv). Read-only.
 */

use GlpiPlugin\Backupinfo\AuditData;
use GlpiPlugin\Backupinfo\AuditPage;
use GlpiPlugin\Backupinfo\AuditPeriod;
use GlpiPlugin\Backupinfo\AuditTable;
use GlpiPlugin\Backupinfo\Csv;
use GlpiPlugin\Backupinfo\ObjectsView;
use GlpiPlugin\Backupinfo\RestoreTest;
use Glpi\Application\View\TemplateRenderer;
use GlpiPlugin\Backupinfo\RightDefinition;
use GlpiPlugin\Backupinfo\TableUi;
use GlpiPlugin\Backupinfo\Xlsx;

include('../../../inc/includes.php');
Session::checkRight(RightDefinition::REPORT, READ);

$live    = []; // 0.3.0-rc7: every section reads GLPI (targets and platform VMs from the daily snapshots)
// Excel sheet names (31 characters at most)
$tabs    = ['policy' => '1 Policy', 'coverage' => '2 Coverage', 'population' => '3 Runs (population)', 'failures' => '4 Failures',
    'restore' => '5 Restore tests', 'copies' => '6 Off-site copies', 'activity' => '7 Changes and alarms', 'targets' => '8 Backup targets'];

$now    = time();
$period = AuditPeriod::parse((string) ($_GET['period'] ?? ''), $now);
$data   = new AuditData($period);
$showOwn = (string) ($_GET['own'] ?? '') === '1';
$data->showOwnLogins($showOwn);
$keep    = ['period' => $period['key']] + ($showOwn ? ['own' => '1'] : []);
$export = (string) ($_GET['export'] ?? '');
$self   = Html::getPrefixedUrl('/plugins/backupinfo/front/audit.php');
$titles = AuditPage::titles();

$meta = static function (string $what) use ($period, $data, $now): array {
    return [
        'Report'         => 'Backup Info audit evidence: ' . $what,
        'Period'         => $period['label'] . ' (' . $period['from'] . ' to ' . $period['to'] . ')',
        'Scope'          => sprintf('%d Computers marked as must be backed up, in the exporting user\'s entities', count($data->computers)),
        'Generated at'   => date('Y-m-d H:i:s', $now),
        'Generated by'   => (string) getUserName(Session::getLoginUserID()), // not glpiname: the web cron can leave "cron" there
        'Connections'    => implode(', ', $data->connectionNames()),
        'Plugin version' => PLUGIN_BACKUPINFO_VERSION,
    ];
};

// Exports: headers and body, then exit, before any HTML.
if ($export === 'all' || in_array($export, AuditPage::SECTIONS, true)) {
    $keys     = $export === 'all' ? AuditPage::SECTIONS : [$export];
    $filename = 'backupinfo-' . $export . '-' . $period['key'];
    $wantCsv  = (string) ($_GET['format'] ?? '') === 'csv';

    if (!$wantCsv && Xlsx::available()) {
        $sheets  = [];
        $summary = [];
        foreach ($keys as $key) {
            $section = $data->section($key);
            $head    = $export === 'all' ? ['Section' => $titles[$key], 'Period' => $period['label']] : $meta($key);
            foreach ($section['errors'] as $i => $error) {
                $head['Read error ' . ($i + 1)] = $error;
            }
            $head['Note'] = $section['note'];
            $sheets[]     = Xlsx::sheet($tabs[$key], $head, $section['columns'], $section['rows']);
            $summary[]    = [$titles[$key], count($section['rows']), implode(' | ', $section['errors'])];
        }
        if ($export === 'all') {
            array_unshift($sheets, Xlsx::sheet('Info', $meta('all sections'), ['Section', 'Rows', 'Read errors'], $summary));
        }
        header('Content-Type: ' . Xlsx::MIME);
        header('Content-Disposition: attachment; filename="' . $filename . '.xlsx"');
        header('Cache-Control: no-store');
        $out = fopen('php://output', 'wb');
        Xlsx::write($out, Xlsx::parts($sheets));
        fclose($out);
        exit;
    }

    // CSV holds one table: "all" without a zip writer gives the population, the core of the evidence.
    $key     = $export === 'all' ? 'population' : $export;
    $section = $data->section($key);
    $head    = $meta($key);
    foreach ($section['errors'] as $i => $error) {
        $head['Read error ' . ($i + 1)] = $error;
    }
    header('Content-Type: text/csv; charset=UTF-8');
    header('Content-Disposition: attachment; filename="backupinfo-' . $key . '-' . $period['key'] . '.csv"');
    header('Cache-Control: no-store');
    echo Csv::render($head, $section);
    exit;
}

// One section's body, fetched by the page below.
if (isset($_GET['section'])) {
    $key = (string) $_GET['section'];
    if (!in_array($key, AuditPage::SECTIONS, true)) {
        http_response_code(400);
        exit;
    }
    $section = $data->section($key);
    $total   = count($section['rows']);
    header('Content-Type: text/html; charset=UTF-8');
    header('Cache-Control: no-store');
    if ($total === 0) {
        echo '<span class="d-none" data-count="0" data-filtered="0"></span>';
        echo '<p class="text-muted">' . htmlescape($section['note']) . '</p>';
        foreach ($section['errors'] as $error) {
            echo '<div class="alert alert-warning">' . htmlescape($error) . '</div>';
        }
        echo '<div class="text-muted">' . __s('Nothing for this period.', 'backupinfo') . '</div>';
        exit;
    }
    // GLPI's own table: filter row, sort and pages on every row; the exports stay complete.
    // Computer names open the GLPI asset (a name shared by two in-scope Computers stays plain);
    // on Restore tests, the test columns open that Computer's restore tests.
    $nameIds = [];
    foreach ($data->computers as $cid => $cname) {
        $nameIds[$cname][] = (int) $cid;
    }
    $compCol  = array_search('Computer', $section['columns'], true);
    $testCols = $key === 'restore' ? array_values(array_filter([
        array_search('Last test', $section['columns'], true),
        array_search('Tests in period', $section['columns'], true),
    ], 'is_int')) : [];
    $canTests = Session::haveRight(RightDefinition::RESTORETEST, READ);
    $links    = static function (array $row) use ($nameIds, $compCol, $testCols, $canTests): array {
        $out = [];
        if (!is_int($compCol)) {
            return $out;
        }
        $ids = $nameIds[(string) ($row[$compCol] ?? '')] ?? [];
        if (count($ids) !== 1) {
            return $out;
        }
        $out[$compCol] = '<a href="' . htmlescape(Computer::getFormURLWithID($ids[0])) . '">' . htmlescape((string) $row[$compCol]) . '</a>';
        foreach ($canTests ? $testCols : [] as $i) {
            $text = (string) ($row[$i] ?? '');
            if ($text !== '' && $text !== '0') {
                $out[$i] = '<a href="' . htmlescape(RestoreTest::getSearchURL() . '?' . ObjectsView::restoreListQuery($ids[0])) . '">' . htmlescape($text) . '</a>';
            }
        }
        return $out;
    };
    $view = AuditTable::view('backupinfo-dt-' . $key, $section, $_GET, (int) ($_SESSION['glpilist_limit'] ?? 15), ['html' => $links]);
    echo '<span class="d-none" data-count="' . $total . '" data-filtered="' . (int) $view['filtered_number'] . '"></span>';
    echo '<p class="text-muted">' . htmlescape($section['note']) . '</p>';
    foreach ($section['errors'] as $error) {
        echo '<div class="alert alert-warning">' . htmlescape($error) . '</div>';
    }
    echo TemplateRenderer::getInstance()->render('components/datatable.html.twig', $view);
    exit;
}

Html::header(__('Audit evidence', 'backupinfo'), '', \GlpiPlugin\Pgnsuite\Menu::SECTOR, 'backupinfo', 'audit');
\GlpiPlugin\Pgnsuite\Menu::renderSubNav('backupinfo', 'audit');

$exportUrl = static fn(string $what, string $format = ''): string => $self . '?' . http_build_query(
    $keep + ['export' => $what] + ($format !== '' ? ['format' => $format] : [])
);

echo '<div class="container-fluid">';
echo '<form method="get" action="' . htmlescape($self) . '" class="d-flex flex-wrap gap-2 align-items-end mb-3">';
echo '<div><label class="form-label" for="backupinfo-period">' . __s('Period', 'backupinfo') . '</label>';
echo '<select class="form-select" id="backupinfo-period" name="period">';
foreach (AuditPeriod::choices($now) as $key => $label) {
    echo '<option value="' . htmlescape((string) $key) . '"' . ((string) $key === $period['key'] ? ' selected' : '') . '>' . htmlescape($label) . '</option>';
}
echo '</select></div>';
echo '<div class="form-check mb-2"><input class="form-check-input" type="checkbox" id="backupinfo-own" name="own" value="1"' . ($showOwn ? ' checked' : '') . '>'
    . '<label class="form-check-label" for="backupinfo-own">' . __s('Show this server\'s logins', 'backupinfo') . '</label></div>';
echo '<button type="submit" class="btn btn-primary">' . __s('Show', 'backupinfo') . '</button>';
echo '<a class="btn btn-outline-success ms-auto" href="' . htmlescape($exportUrl('all')) . '"><i class="ti ti-file-spreadsheet"></i> '
    . __s('Export all sections (Excel)', 'backupinfo') . '</a>';
echo '</form>';

echo '<div class="alert alert-info">' . htmlescape(sprintf(
    __('Period %1$s (%2$s to %3$s). In scope: %4$d computers that must be backed up, in your active entities.', 'backupinfo'),
    $period['label'],
    $period['from'],
    $period['to'],
    count($data->computers)
)) . '</div>';
$scopeNote = AuditPage::scopeNote($data->mandatoryTotal, count($data->computers));
if ($scopeNote !== null) {
    echo '<div class="alert alert-warning">' . htmlescape($scopeNote) . '</div>';
}

// One tab per section; every section still loads in the background.
echo '<ul class="nav nav-tabs mb-3" role="tablist">';
foreach ($titles as $key => $title) {
    echo '<li class="nav-item" role="presentation"><button type="button" class="nav-link' . ($key === 'policy' ? ' active' : '') . '" data-bs-toggle="tab" data-bs-target="#backupinfo-audit-' . $key . '" role="tab">' . htmlescape($title) . '</button></li>';
}
echo '</ul><div class="tab-content">';

foreach ($titles as $key => $title) {
    echo '<div class="tab-pane' . ($key === 'policy' ? ' show active' : '') . '" role="tabpanel" id="backupinfo-audit-' . $key . '"><div class="card mb-3">';
    echo '<div class="card-header d-flex justify-content-between align-items-center">';
    echo '<h3 class="card-title">' . htmlescape($title) . ' <span class="text-muted" id="backupinfo-audit-count-' . $key . '"></span></h3>';
    echo '<div class="d-flex gap-2">';
    // Columns shown on screen, kept per section in this browser; the exports keep every column.
    echo TableUi::columnsButton('backupinfo-audit-cols-' . $key);

    echo '<div class="btn-group">';
    echo '<a class="btn btn-sm btn-outline-success" href="' . htmlescape($exportUrl($key)) . '"><i class="ti ti-file-spreadsheet"></i> ' . __s('Excel', 'backupinfo') . '</a>';
    echo '<a class="btn btn-sm btn-outline-secondary" href="' . htmlescape($exportUrl($key, 'csv')) . '">' . __s('CSV', 'backupinfo') . '</a>';
    echo '</div></div></div>';
    echo '<div class="card-body" id="backupinfo-audit-body-' . $key . '"><div class="text-muted"><span class="spinner-border spinner-border-sm me-2"></span>'
        . (in_array($key, $live, true) ? __s('Reading the backup system...', 'backupinfo') : __s('Loading...', 'backupinfo')) . '</div></div>';
    echo '</div></div>';
}
echo '</div></div>';

// GLPI sections first, then the live reads; one at a time (the session serialises them anyway).
$order = array_merge(array_values(array_diff(AuditPage::SECTIONS, $live)), $live);
$js = static fn(mixed $v): string => json_encode($v, JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT);
echo Html::scriptBlock(TableUi::script());
echo Html::scriptBlock('(() => {
    const T = window.backupinfoTable;
    const base = ' . $js($self . '?' . http_build_query($keep)) . ';
    const failed = ' . $js(__('This section could not be loaded. Reload the page or use the export.', 'backupinfo')) . ';
    const ofText = ' . $js(__('%1$d of %2$d', 'backupinfo')) . ';
    const showAll = ' . $js(__('Show all columns', 'backupinfo')) . ';
    const state = {};
    const store = (key) => "backupinfo.audit.cols." + key; // columns hidden on screen, per section, in this browser

    const load = async (key) => {
        const body = document.getElementById("backupinfo-audit-body-" + key), st = state[key];
        try {
            const res = await fetch(base + "&section=" + encodeURIComponent(key) + "&" + T.query(st), {credentials: "same-origin"});
            if (!res.ok) {
                throw new Error(String(res.status));
            }
            $(body).find(".filter_row .select2-hidden-accessible").select2("close");
            $(body).html(await res.text()); // jQuery runs the table\'s own script (select2 on the choice filters)
            const count = body.querySelector("[data-count]");
            if (count) {
                const total = Number(count.dataset.count), shown = Number(count.dataset.filtered);
                document.getElementById("backupinfo-audit-count-" + key).textContent = "(" + (shown === total ? total : ofText.replace("%1$d", shown).replace("%2$d", total)) + ")";
            }
            if (st.limit) { $(body).find("select[name=list_limit]").val(st.limit); }
            T.colMenu(store(key), body, document.getElementById("backupinfo-audit-cols-" + key), showAll);
            T.applyCols(store(key), body);
        } catch (e) {
            body.innerHTML = "";
            const div = document.createElement("div");
            div.className = "alert alert-danger";
            div.textContent = failed;
            body.appendChild(div);
        }
    };

    // GLPI\'s table calls reloadTab() for sort, pages, page size and filters; this page has no item
    // tabs, so it is defined here for the section on screen.
    window.reloadTab = (add) => {
        const pane = document.querySelector(".tab-pane.active[id^=\"backupinfo-audit-\"]");
        const key = pane ? pane.id.replace("backupinfo-audit-", "") : null;
        if (!key || !state[key]) { return; }
        state[key] = T.step(state[key], add);
        load(key);
    };

    (async () => {
        for (const key of ' . $js($order) . ') {
            state[key] = {filters: "", sort: "", order: "ASC", start: 0, limit: ""};
            T.bindFilters($("#backupinfo-audit-body-" + key), (add) => window.reloadTab(add));
            await load(key);
        }
    })();
})();');

Html::footer();